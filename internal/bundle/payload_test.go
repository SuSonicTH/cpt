func TestPayloadRoundTrip(t *testing.T) {
	dir := t.TempDir()
	bin := filepath.Join(dir, "tool")
	if err := os.WriteFile(bin, []byte("#!/bin/sh\necho hi\n"), 0o755); err != nil {
		t.Fatal(err)
	}
	listData := []byte(`{"schema":1,"name":"core","packages":[]}`)
	m := testManifest("devbox", true)
	m.Packages = []ManifestPackage{{
		Name: "tool", Version: "1.0.0", Tag: "v1.0.0", Asset: "tool.tar.gz",
		DownloadSHA256: strings.Repeat("a", 64), Bins: []string{"tool"}, ChecksumStatus: "tofu",
	}}
	m.Lists = map[string]ManifestList{"core": {SHA256: hashFor(listData), Origin: "https://example.com/core.json"}}

	var buf bytes.Buffer
	if err := WritePayload(&buf, Payload{
		Manifest: m,
		Lists:    map[string][]byte{"core": listData},
		Bins:     []PayloadBin{{Name: "tool", Path: bin}},
		Init:     map[string][]byte{"cptinit.sh": []byte("# generated by cpt\n")},
	}); err != nil {
		t.Fatalf("WritePayload: %v", err)
	}

	dest := t.TempDir()
	got, err := ExtractPayload(&buf, dest)
	if err != nil {
		t.Fatalf("ExtractPayload: %v", err)
	}
	if got.Name != "devbox" || !got.Frozen || len(got.Packages) != 1 {
		t.Fatalf("unexpected manifest: %+v", got)
	}
	data, err := os.ReadFile(filepath.Join(dest, "bin", "tool"))
	if err != nil || string(data) != "#!/bin/sh\necho hi\n" {
		t.Fatalf("binary round trip: %v %q", err, data)
	}
	if _, err := os.Stat(filepath.Join(dest, "lists", "core.json")); err != nil {
		t.Fatalf("list missing: %v", err)
	}
}

func TestExtractPayloadRejectsTraversal(t *testing.T) {
	var buf bytes.Buffer
	enc, err := zstd.NewWriter(&buf)
	if err != nil {
		t.Fatal(err)
	}
	tw := tar.NewWriter(enc)
	body := []byte("x")
	if err := tw.WriteHeader(&tar.Header{Name: "../escape", Mode: 0o644, Size: int64(len(body)), Typeflag: tar.TypeReg}); err != nil {
		t.Fatal(err)
	}
	tw.Write(body)
	tw.Close()
	enc.Close()

	dest := t.TempDir()
	if _, err := ExtractPayload(&buf, dest); err == nil {
		t.Fatal("path traversal entry accepted")
	}
	if _, err := os.Stat(filepath.Join(dest, "..", "escape")); err == nil {
		t.Fatal("traversal wrote outside the destination")
	}
}

func TestExtractPayloadRejectsListHashMismatch(t *testing.T) {
	listData := []byte(`{"schema":1,"name":"core","packages":[]}`)
	m := testManifest("broken", false)
	m.Lists = map[string]ManifestList{"core": {SHA256: strings.Repeat("0", 64)}}

	var buf bytes.Buffer
	if err := WritePayload(&buf, Payload{Manifest: m, Lists: map[string][]byte{"core": listData}}); err != nil {
		t.Fatal(err)
	}
	if _, err := ExtractPayload(&buf, t.TempDir()); err == nil {
		t.Fatal("list hash mismatch accepted")
	}
}

func TestReadManifestVerifiesContainer(t *testing.T) {
	m := testManifest("inspect", true)
	path := buildTestFile(t, t.TempDir(), "base", Payload{Manifest: m, Lists: map[string][]byte{}})
	c, err := Open(path)
	if err != nil {
		t.Fatal(err)
	}
	defer c.Close()
	got, err := ReadManifest(c)
	if err != nil {
		t.Fatal(err)
	}
	if got.Name != "inspect" || !got.Frozen {
		t.Fatalf("unexpected manifest: %+v", got)
	}
}
