func TestInitInstallIsIdempotent(t *testing.T) {
	root := t.TempDir()
	rc := filepath.Join(root, "bashrc")
	if err := os.WriteFile(rc, []byte("# existing\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	for i := 0; i < 2; i++ {
		var out, errb bytes.Buffer
		if code := Run(context.Background(), []string{"--root", root, "init", "bash", "--install", "--file", rc}, &out, &errb); code != 0 {
			t.Fatalf("install pass %d: exit %d, stderr %s", i, code, errb.String())
		}
	}
	data, err := os.ReadFile(rc)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Count(string(data), shellinit.BeginMarker) != 1 {
		t.Fatalf("marker block is not idempotent:\n%s", data)
	}
	if _, err := os.Stat(filepath.Join(root, "cptinit.sh")); err != nil {
		t.Fatalf("cptinit.sh was not generated: %v", err)
	}

	var out, errb bytes.Buffer
	if code := Run(context.Background(), []string{"--root", root, "init", "bash", "--uninstall", "--file", rc}, &out, &errb); code != 0 {
		t.Fatalf("uninstall: exit %d, stderr %s", code, errb.String())
	}
	data, _ = os.ReadFile(rc)
	if string(data) != "# existing\n" {
		t.Fatalf("uninstall left unexpected content: %q", data)
	}
}

func TestInitPrintsScript(t *testing.T) {
	root := t.TempDir()
	var out, errb bytes.Buffer
	if code := Run(context.Background(), []string{"--root", root, "init", "zsh"}, &out, &errb); code != 0 {
		t.Fatalf("exit %d, stderr %s", code, errb.String())
	}
	script := out.String()
	if !strings.Contains(script, "# generated by cpt") || !strings.Contains(script, "export CPT_HOME='"+root+"'") {
		t.Fatalf("unexpected script:\n%s", script)
	}
}

func TestShellStatusDiffAndApprove(t *testing.T) {
	root := t.TempDir()
	st := state.New()
	st.Packages["mytool"] = &state.Package{Version: "1.0.0", Bins: map[string]string{}}
	st.Shell["mytool"] = &state.Shell{
		Approved:      false,
		SnippetSHA256: shellinit.Bodies{Bash: "export OLD=1\n"}.Hash(),
		Live:          &state.ShellSnippet{Version: "1.0.0", Bash: "export OLD=1\n"},
		Pending:       &state.ShellSnippet{Version: "1.1.0", Bash: "export NEW=1\n"},
		PendingSHA256: shellinit.Bodies{Bash: "export NEW=1\n"}.Hash(),
	}
	if err := st.Save(filepath.Join(root, "state.json")); err != nil {
		t.Fatal(err)
	}

	var out, errb bytes.Buffer
	if code := Run(context.Background(), []string{"--root", root, "--json", "shell"}, &out, &errb); code != 0 {
		t.Fatalf("shell list: exit %d, stderr %s", code, errb.String())
	}
	var env struct {
		OK   bool `json:"ok"`
		Data struct {
			Enabled  bool `json:"enabled"`
			Snippets []struct {
				Package string `json:"package"`
				Pending bool   `json:"pending"`
			} `json:"snippets"`
		} `json:"data"`
	}
	if err := json.Unmarshal(out.Bytes(), &env); err != nil {
		t.Fatalf("invalid JSON: %v\n%s", err, out.String())
	}
	if !env.OK || !env.Data.Enabled || len(env.Data.Snippets) != 1 || !env.Data.Snippets[0].Pending {
		t.Fatalf("unexpected shell status: %+v", env)
	}

	out.Reset()
	errb.Reset()
	if code := Run(context.Background(), []string{"--root", root, "shell", "diff", "mytool"}, &out, &errb); code != 0 {
		t.Fatalf("shell diff: exit %d, stderr %s", code, errb.String())
	}
	if !strings.Contains(out.String(), "-export OLD=1") || !strings.Contains(out.String(), "+export NEW=1") {
		t.Fatalf("unexpected diff:\n%s", out.String())
	}

	out.Reset()
	errb.Reset()
	if code := Run(context.Background(), []string{"--root", root, "shell", "approve", "mytool"}, &out, &errb); code != 0 {
		t.Fatalf("shell approve: exit %d, stderr %s", code, errb.String())
	}
	saved, err := state.Load(filepath.Join(root, "state.json"))
	if err != nil {
		t.Fatal(err)
	}
	sh := saved.Shell["mytool"]
	if sh == nil || sh.Pending != nil || !strings.Contains(sh.Live.Bash, "NEW") {
		t.Fatalf("approval was not persisted: %+v", sh)
	}
	script, err := os.ReadFile(filepath.Join(root, "cptinit.sh"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(script), "export NEW=1") || strings.Contains(string(script), "export OLD=1") {
		t.Fatalf("cptinit was not regenerated:\n%s", script)
	}
}

func TestInitRefusesCustomRootWithoutFile(t *testing.T) {
	root := t.TempDir()
	var out, errb bytes.Buffer
	code := Run(context.Background(), []string{"--root", root, "init", "bash", "--install"}, &out, &errb)
	if code != 2 {
		t.Fatalf("exit = %d, want 2; stderr=%s", code, errb.String())
	}
	if !strings.Contains(errb.String(), "--file") {
		t.Fatalf("error does not mention --file: %s", errb.String())
	}
}

