// Package shellinit renders cptinit scripts and edits shell rc marker blocks.
package shellinit

import (
	"context"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
	"time"
	"unicode"
)

// Flavor is a snippet dialect. zsh uses the bash dialect.
type Flavor string

const (
	// FlavorBash is the POSIX sh/bash/zsh dialect.
	FlavorBash Flavor = "bash"
	// FlavorPwsh is the PowerShell dialect.
	FlavorPwsh Flavor = "pwsh"
)

// Shell is a user-facing shell name.
type Shell string

const (
	// ShellBash is bash.
	ShellBash Shell = "bash"
	// ShellZsh is zsh.
	ShellZsh Shell = "zsh"
	// ShellPwsh is PowerShell 7+.
	ShellPwsh Shell = "pwsh"
	// ShellPowerShell is Windows PowerShell 5.1.
	ShellPowerShell Shell = "powershell"
)

// IsPowerShell reports whether the shell uses the pwsh snippet dialect.
func (s Shell) IsPowerShell() bool { return s == ShellPwsh || s == ShellPowerShell }

// ParsedShell accepts a shell name from the command line.
func ParsedShell(s string) (Shell, error) {
	switch strings.ToLower(strings.TrimSpace(s)) {
	case "bash":
		return ShellBash, nil
	case "zsh":
		return ShellZsh, nil
	case "pwsh":
		return ShellPwsh, nil
	case "powershell", "ps5":
		return ShellPowerShell, nil
	case "fish":
		return "", fmt.Errorf("fish is not supported yet")
	default:
		return "", fmt.Errorf("unsupported shell %q (want bash, zsh, pwsh or powershell)", s)
	}
}

// Flavor returns the snippet dialect for the shell.
func (s Shell) Flavor() Flavor {
	if s.IsPowerShell() {
		return FlavorPwsh
	}
	return FlavorBash
}

// String returns the shell name.
func (s Shell) String() string { return string(s) }

// RCPath returns the default startup file for the shell.
func (s Shell) RCPath(home string) string {
	switch s {
	case ShellZsh:
		return filepath.Join(home, ".zshrc")
	case ShellPwsh:
		if runtime.GOOS == "windows" {
			return filepath.Join(home, "Documents", "PowerShell", "Microsoft.PowerShell_profile.ps1")
		}
		return filepath.Join(home, ".config", "powershell", "Microsoft.PowerShell_profile.ps1")
	case ShellPowerShell:
		if runtime.GOOS == "windows" {
			return filepath.Join(home, "Documents", "WindowsPowerShell", "Microsoft.PowerShell_profile.ps1")
		}
		return filepath.Join(home, ".config", "powershell", "Microsoft.PowerShell_profile.ps1")
	default:
		return filepath.Join(home, ".bashrc")
	}
}

// ScriptName is the generated init file name for a flavor.
func ScriptName(f Flavor) string {
	if f == FlavorPwsh {
		return "cptinit.ps1"
	}
	return "cptinit.sh"
}

// Options supplies the paths written into a generated script.
type Options struct {
	Root string
	Bin  string
	Home string
}

// Block is one approved package snippet.
type Block struct {
	Name    string
	Version string
	SHA256  string
	Body    string
}

// Render produces a complete cptinit script. Blocks are emitted in package
// name order so that diffs stay small.
func Render(f Flavor, opt Options, blocks []Block) string {
	sorted := make([]Block, 0, len(blocks))
	for _, b := range blocks {
		if strings.TrimSpace(b.Body) != "" {
			sorted = append(sorted, b)
		}
	}
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Name < sorted[j].Name })

	var b strings.Builder
	if f == FlavorPwsh {
		renderPwshHeader(&b, opt)
	} else {
		renderBashHeader(&b, opt)
	}
	for _, blk := range sorted {
		name := markerSafe(blk.Name)
		version := VersionLabel(markerSafe(blk.Version))
		b.WriteString("\n")
		if version != "" {
			fmt.Fprintf(&b, "# >>> cpt:%s %s sha256:%s\n", name, version, shortHash(blk.SHA256))
		} else {
			fmt.Fprintf(&b, "# >>> cpt:%s sha256:%s\n", name, shortHash(blk.SHA256))
		}
		b.WriteString(ensureTrailingNewline(blk.Body))
		fmt.Fprintf(&b, "# <<< cpt:%s\n", name)
	}
	return b.String()
}

// ScriptBytes returns the on-disk representation of a generated script.
// Windows PowerShell 5.1 treats BOM-less UTF-8 as the legacy ANSI code page,
// so cptinit.ps1 is written with a UTF-8 BOM. The bash script stays plain
// UTF-8, and cpt init still prints the script itself without a BOM.
func ScriptBytes(f Flavor, script string) []byte {
	if f == FlavorPwsh {
		return append([]byte{0xEF, 0xBB, 0xBF}, script...)
	}
	return []byte(script)
}

// DecodeScript strips a UTF-8 BOM from a generated script before comparing it
// with freshly rendered output.
func DecodeScript(data []byte) string {
	return strings.TrimPrefix(string(data), "\ufeff")
}

// HasUTF8BOM reports whether data starts with a UTF-8 byte order mark.
func HasUTF8BOM(data []byte) bool {
	return len(data) >= 3 && data[0] == 0xEF && data[1] == 0xBB && data[2] == 0xBF
}

func renderBashHeader(b *strings.Builder, opt Options) {
	b.WriteString("# generated by cpt — do not edit\n")
	if isDefaultRoot(opt) {
		b.WriteString("export CPT_HOME=\"$HOME/.cpt\"\n")
	} else {
		fmt.Fprintf(b, "export CPT_HOME=%s\n", posixQuote(opt.Root))
	}
	bin := effectiveBin(opt)
	if bin == filepath.Join(opt.Root, "bin") {
		b.WriteString("case \":$PATH:\" in *\":$CPT_HOME/bin:\"*) ;; *) PATH=\"$CPT_HOME/bin:$PATH\" ;; esac\n")
	} else {
		q := posixQuote(bin)
		fmt.Fprintf(b, "case \":$PATH:\" in *:%s:*) ;; *) PATH=%s:\"$PATH\" ;; esac\n", q, q)
	}
	b.WriteString("export PATH\n")
}

func renderPwshHeader(b *strings.Builder, opt Options) {
	// ASCII keeps the file readable in Windows PowerShell 5.1, which does not
	// default to UTF-8 for BOM-less scripts.
	b.WriteString("# generated by cpt - do not edit\n")
	if isDefaultRoot(opt) {
		b.WriteString("$env:CPT_HOME = Join-Path $HOME '.cpt'\n")
	} else {
		fmt.Fprintf(b, "$env:CPT_HOME = %s\n", pwshQuote(opt.Root))
	}
	if effectiveBin(opt) == filepath.Join(opt.Root, "bin") {
		b.WriteString("$cptBin = Join-Path $env:CPT_HOME 'bin'\n")
	} else {
		fmt.Fprintf(b, "$cptBin = %s\n", pwshQuote(effectiveBin(opt)))
	}
	b.WriteString("if (($env:PATH -split [IO.Path]::PathSeparator) -notcontains $cptBin) { $env:PATH = $cptBin + [IO.Path]::PathSeparator + $env:PATH }\n")
}

func effectiveBin(opt Options) string {
	if opt.Bin == "" {
		return filepath.Join(opt.Root, "bin")
	}
	return opt.Bin
}

func isDefaultRoot(opt Options) bool {
	if opt.Home == "" || opt.Root == "" {
		return false
	}
	home := filepath.Clean(opt.Home)
	return filepath.Clean(opt.Root) == filepath.Join(home, ".cpt")
}

func shortHash(hash string) string {
	hash = strings.ToLower(strings.TrimSpace(hash))
	if hash == "" {
		return "unknown"
	}
	for _, r := range hash {
		if !((r >= '0' && r <= '9') || (r >= 'a' && r <= 'f')) {
			return "unknown"
		}
	}
	if len(hash) > 8 {
		return hash[:8]
	}
	return hash
}

// VersionLabel renders a version with exactly one leading v.
func VersionLabel(v string) string {
	v = strings.Map(func(r rune) rune {
		if unicode.IsControl(r) || unicode.Is(unicode.Cf, r) || r == '\u2028' || r == '\u2029' {
			return -1
		}
		return r
	}, v)
	v = strings.TrimSpace(v)
	if v == "" {
		return ""
	}
	if v[0] == 'v' || v[0] == 'V' {
		return v
	}
	return "v" + v
}

// ShortHash abbreviates a digest for display, or returns "" when empty.
func ShortHash(hash string) string {
	if strings.TrimSpace(hash) == "" {
		return ""
	}
	return shortHash(hash)
}

// markerSafe keeps a package name or version from ending the marker comment.
func markerSafe(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch {
		case unicode.IsControl(r), unicode.Is(unicode.Cf, r), unicode.IsSpace(r), r == '\u2028', r == '\u2029':
			b.WriteByte('_')
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

func ensureTrailingNewline(s string) string {
	s = strings.TrimRight(s, "\r\n")
	if s == "" {
		return ""
	}
	return s + "\n"
}

// Marker block lines used in rc files. The opt-in editor only ever writes and
// removes this exact pair; snippet bodies live in the generated cptinit file.
const (
	BeginMarker = "# >>> cpt:init"
	EndMarker   = "# <<< cpt:init"
)

// MarkerBlock renders the opt-in rc-file block for a shell.
func MarkerBlock(sh Shell, scriptPath string, opt Options) string {
	ref := scriptRef(scriptPath, opt)
	if sh.IsPowerShell() {
		line := fmt.Sprintf("if (Test-Path %s) { . %s }", ref, ref)
		return BeginMarker + "\n" + line + "\n" + EndMarker + "\n"
	}
	line := fmt.Sprintf("[ -f %s ] && . %s", ref, ref)
	return BeginMarker + "\n" + line + "\n" + EndMarker + "\n"
}

func scriptRef(path string, opt Options) string {
	if isDefaultRoot(opt) && filepath.Clean(path) == filepath.Join(opt.Root, ScriptName(FlavorBash)) {
		return "\"$HOME/.cpt/cptinit.sh\""
	}
	if isDefaultRoot(opt) && filepath.Clean(path) == filepath.Join(opt.Root, ScriptName(FlavorPwsh)) {
		return "\"$HOME/.cpt/cptinit.ps1\""
	}
	// PowerShell accepts single-quoted paths; for bash this is also valid.
	if strings.HasSuffix(path, ".ps1") {
		return pwshQuote(path)
	}
	return posixQuote(path)
}

// HasBlock reports whether content contains a complete cpt init marker block.
func HasBlock(content string) bool {
	_, _, ok := findBlock(splitLines(content))
	return ok
}

// AddBlock appends the marker block, replacing an existing one. Repeated calls
// are idempotent.
func AddBlock(content, block string) string {
	eol := detectEOL(content)
	content = RemoveBlock(content)
	block = normalizeEOL(strings.TrimLeft(block, "\r\n"), eol)
	if content != "" && !strings.HasSuffix(content, "\n") {
		content += eol
	}
	return content + block
}

// RemoveBlock removes every complete cpt init marker block. A begin marker
// without a matching end before the next begin marker is left untouched rather
// than swallowing unrelated user configuration.
func RemoveBlock(content string) string {
	for {
		lines := splitLines(content)
		start, end, ok := findBlock(lines)
		if !ok {
			return content
		}
		content = strings.Join(lines[:start], "") + strings.Join(lines[end+1:], "")
	}
}

func findBlock(lines []string) (int, int, bool) {
	for i := 0; i < len(lines); i++ {
		if !isBeginLine(lines[i]) {
			continue
		}
		end := -1
		for j := i + 1; j < len(lines); j++ {
			if isBeginLine(lines[j]) {
				// A nested begin means this one is malformed. Skip it and let
				// the outer loop try the later marker.
				break
			}
			if strings.HasPrefix(lineText(lines[j]), EndMarker) {
				end = j
				break
			}
		}
		if end >= 0 {
			return i, end, true
		}
	}
	return 0, 0, false
}

func isBeginLine(line string) bool {
	text := lineText(line)
	return text == BeginMarker || strings.HasPrefix(text, BeginMarker+" ")
}

func splitLines(s string) []string {
	var lines []string
	for len(s) > 0 {
		i := strings.IndexByte(s, '\n')
		if i < 0 {
			lines = append(lines, s)
			break
		}
		lines = append(lines, s[:i+1])
		s = s[i+1:]
	}
	return lines
}

func lineText(line string) string { return strings.TrimRight(line, "\r\n") }

func detectEOL(s string) string {
	if strings.Contains(s, "\r\n") {
		return "\r\n"
	}
	return "\n"
}

func normalizeEOL(s, eol string) string {
	s = strings.ReplaceAll(s, "\r\n", "\n")
	s = strings.ReplaceAll(s, "\r", "\n")
	if eol == "\n" {
		return s
	}
	return strings.ReplaceAll(s, "\n", eol)
}

func posixQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

func pwshQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}

// ExpandPath expands a leading ~ and makes the result absolute.
func ExpandPath(path, home string) string {
	if path == "~" {
		path = home
	} else if strings.HasPrefix(path, "~/") || strings.HasPrefix(path, `~\`) {
		path = filepath.Join(home, path[2:])
	}
	if abs, err := filepath.Abs(path); err == nil {
		return abs
	}
	return path
}

// HomeDir returns the current user's home directory.
func HomeDir() (string, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", fmt.Errorf("determine home directory: %w", err)
	}
	if strings.TrimSpace(home) == "" {
		return "", fmt.Errorf("home directory is not set")
	}
	return home, nil
}

// ProfilePath resolves the startup file to edit. PowerShell exports $PROFILE,
// which can differ from the default path (PowerShell 5.1, OneDrive redirects,
// custom profiles), so prefer asking pwsh when it is installed.
func ProfilePath(ctx context.Context, sh Shell, home string) (string, error) {
	if sh.IsPowerShell() {
		primary, secondary := "pwsh", "powershell"
		if sh == ShellPowerShell {
			primary, secondary = "powershell", "pwsh"
		}
		if path := queryProfile(ctx, primary); path != "" {
			return path, nil
		}
		// Only consult the other executable when the requested one is absent.
		// Falling back after a failed query could edit the wrong profile.
		if _, err := exec.LookPath(primary); err != nil {
			if path := queryProfile(ctx, secondary); path != "" {
				return path, nil
			}
		}
	}
	if home == "" {
		return "", fmt.Errorf("home directory is not set; pass --file")
	}
	return sh.RCPath(home), nil
}

func queryProfile(ctx context.Context, name string) string {
	exe, err := exec.LookPath(name)
	if err != nil {
		return ""
	}
	runCtx, cancel := context.WithTimeout(ctx, 5*time.Second)
	defer cancel()
	out, err := exec.CommandContext(runCtx, exe, "-NoLogo", "-NoProfile", "-NonInteractive", "-Command", "$PROFILE").Output()
	if err != nil {
		return ""
	}
	return strings.TrimSpace(string(out))
}
